builder = FontBuilder(1000, isTTF=True)
names = {char: 'space' if char==' ' else f'uni{ord(char):04X}' for char in rows}
order = ['.notdef'] + list(names.values())
builder.setupGlyphOrder(order)
builder.setupCharacterMap({ord(c): n for c,n in names.items()})
glyphs = {'.notdef': TTGlyphPen(None).glyph()}
metrics = {'.notdef':(600,0)}
for char, pattern in rows.items():
    pen=TTGlyphPen(None)
    for y,row in enumerate(pattern):
        for x,cell in enumerate(row):
            if cell=='1':
                left=x*100; bottom=(6-y)*100
                pen.moveTo((left,bottom));pen.lineTo((left,bottom+100));pen.lineTo((left+100,bottom+100));pen.lineTo((left+100,bottom));pen.closePath()
    glyphs[names[char]]=pen.glyph()
    metrics[names[char]]=(350 if char==' ' else 600,0)
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics(metrics)
builder.setupHorizontalHeader(ascent=850,descent=-150)
builder.setupNameTable({'familyName':'Sift Pixel','styleName':'Regular','uniqueFontIdentifier':'SiftPixel-2026','fullName':'Sift Pixel Regular','psName':'SiftPixel-Regular','version':'Version 1.0','copyright':'Original display lettering created for the Sift website.'})
